    'Total inertia:              %.6e kg*m^2\n', ...
    motor.J ...
);


fprintf( ...
    'Viscous friction:           %.6e N*m*s/rad\n', ...
    motor.B ...
);


fprintf( ...
    'Rated speed:                %.0f RPM\n', ...
    motor.ratedSpeedRPM ...
);


fprintf( ...
    'Rated current:              %.2f A\n', ...
    motor.ratedCurrent ...
);


fprintf('\nSteady-state conditions:\n');

fprintf('di/dt     = 0\n');

fprintf('domega/dt = 0\n');


fprintf( ...
    'Operating points:           %d\n', ...
    simulation.numberOfOperatingPoints ...
);


%% ========================================================================
%  ========================================================================
%
%                              CASE 1
%
%                CONSTANT 24 V + LOAD TORQUE SWEEP
