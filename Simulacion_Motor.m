%% ========================================================================
%  LOCAL FUNCTION
%
%  STEADY-STATE OPERATING POINT
%
%  The steady-state equations are:
%
%       0 = V - R*i - Ke*omega
%
%       0 = Kt*i - B*omega - Tload
%
%
%  NORMAL REGION:
%
%       Voltage = commanded voltage
%
%
%  CURRENT-LIMITED REGION:
%
%       i = Imax
%
%
%  STALL:
%
%       omega = 0
%
% ========================================================================

function [ ...
    current, ...
    angularVelocity, ...
    effectiveVoltage, ...
    currentLimitActive, ...
    stalled ...
    ] = steadyStateOperatingPoint( ...
        commandedVoltage, ...
        loadTorque, ...
        motor, ...
        minimumCurrent, ...
        maximumCurrent ...
    )


    tolerance = 1e-10;


    %% Ensure nonnegative inputs

    commandedVoltage = ...
        max( ...
            commandedVoltage, ...
            0 ...
        );


    loadTorque = ...
        max( ...
            loadTorque, ...
            0 ...
        );


    %% ====================================================================
    %  UNCONSTRAINED STEADY-STATE SOLUTION
    %
    %       V = R*i + Ke*omega
    %
    %       Kt*i = B*omega + Tload
    %
    %
    %  Eliminating current:
    %
    %                   V - R*Tload/Kt
    %       omega = -------------------------
    %                  Ke + R*B/Kt
    %
    % =====================================================================

    denominator = ...
        motor.Ke + ...
        motor.R * ...
        motor.B / ...
        motor.Kt;


    unconstrainedAngularVelocity = ...
        ( ...
            commandedVoltage - ...
            motor.R * ...
            loadTorque / ...
            motor.Kt ...
        ) / ...
        denominator;


    %% Calculate required current

    if unconstrainedAngularVelocity > 0

        unconstrainedCurrent = ...
            ( ...
                loadTorque + ...
                motor.B * ...
                unconstrainedAngularVelocity ...
            ) / ...
            motor.Kt;

    else

        % At stall:
        %
        %       omega = 0
        %
        % therefore:
        %
        %       i = V/R

        unconstrainedCurrent = ...
            commandedVoltage / ...
            motor.R;

    end


    %% ====================================================================
    %  NORMAL VOLTAGE-LIMITED OPERATING REGION
    % =====================================================================

    if ...
        unconstrainedAngularVelocity > 0 ...
        && ...
        unconstrainedCurrent <= ...
        maximumCurrent + tolerance


        angularVelocity = ...
            unconstrainedAngularVelocity;


        current = ...
            min( ...
                max( ...
                    unconstrainedCurrent, ...
                    minimumCurrent ...
                ), ...
                maximumCurrent ...
            );


        effectiveVoltage = ...
            commandedVoltage;


        currentLimitActive = ...
            false;


        stalled = ...
            false;


        return;

    end


    %% ====================================================================
    %  CURRENT-LIMITED OPERATING REGION
    %
    %       i = Imax
    %
    %
    %  Mechanical steady-state equation:
    %
    %       Kt*Imax = B*omega + Tload
    %
    %
    %  Therefore:
    %
    %                  Kt*Imax - Tload
    %       omega = --------------------------
    %                          B
    %
    % =====================================================================

    if unconstrainedCurrent > maximumCurrent

        current = ...
            maximumCurrent;


        currentLimitedAngularVelocity = ...
            ( ...
                motor.Kt * ...
                current - ...
                loadTorque ...
            ) / ...
            motor.B;


        if currentLimitedAngularVelocity > 0

            requiredVoltage = ...
                motor.R * ...
                current + ...
                motor.Ke * ...
                currentLimitedAngularVelocity;


            if requiredVoltage <= ...
                    commandedVoltage + tolerance


                angularVelocity = ...
                    currentLimitedAngularVelocity;


                effectiveVoltage = ...
                    max( ...
                        requiredVoltage, ...
                        0 ...
                    );


                currentLimitActive = ...
                    true;


                stalled = ...
                    false;


                return;

            end

        end

    end


    %% ====================================================================
    %  STALL CONDITION
%  ========================================================================

    angularVelocity = 0;


    current = ...
        commandedVoltage / ...
        motor.R;


    current = ...
        min( ...
            max( ...
                current, ...
                minimumCurrent ...
            ), ...
            maximumCurrent ...
        );


    effectiveVoltage = ...
        motor.R * ...
        current;


    currentLimitActive = ...
        current >= ...
        maximumCurrent - tolerance ...
        && ...
        commandedVoltage > ...
        effectiveVoltage + tolerance;


    stalled = true;

end