%% ========================================================================
%  10. CASE 1 PARAMETERS
%  ========================================================================

case1.voltage = 24;             % [V]

case1.initialLoadTorque = 0.00; % [N*m]

case1.finalLoadTorque = 0.2;    % [N*m]

case1.minimumCurrent = 0;       % [A]


%% ========================================================================
%  CASE 1 CURRENT LIMIT SELECTION
%  ========================================================================

% -------------------------------------------------------------------------
%
% ACTIVE:
%
%       Driver current limit = 1 A
%
% COMMENT THIS LINE:
%
%       Motor rated-current limit = 4.8 A
%
% -------------------------------------------------------------------------

case1.maximumCurrent = 1.0;     % DRIVER LIMIT - COMMENT FOR 4.8 A


if ~isfield(case1,'maximumCurrent')

    case1.maximumCurrent = ...
        motor.ratedCurrent;

end


if abs(case1.maximumCurrent - 1.0) < 1e-9

    case1.currentLimitSource = ...
        'Driver limit';

elseif abs( ...
        case1.maximumCurrent - ...
        motor.ratedCurrent ...
        ) < 1e-9

    case1.currentLimitSource = ...
        'Motor rated current';

else

    case1.currentLimitSource = ...
        'Custom current limit';

end


%% ========================================================================
%  11. CASE 1 LOAD TORQUE SWEEP
%  ========================================================================

loadTorque1 = linspace( ...
    case1.initialLoadTorque, ...
    case1.finalLoadTorque, ...
    simulation.numberOfOperatingPoints ...
).';


commandedVoltage1 = ...
    case1.voltage * ...
    ones(size(loadTorque1));


%% ========================================================================
%  12. CASE 1 STEADY-STATE SOLUTION
%  ========================================================================

numberOfSamples1 = ...
    length(loadTorque1);


current1 = ...
    zeros(numberOfSamples1,1);


angularVelocity1 = ...
    zeros(numberOfSamples1,1);


effectiveVoltage1 = ...
    zeros(numberOfSamples1,1);


currentLimitActive1 = ...
    false(numberOfSamples1,1);


stalledState1 = ...
    false(numberOfSamples1,1);


for k = 1:numberOfSamples1

    [ ...
        current1(k), ...
        angularVelocity1(k), ...
        effectiveVoltage1(k), ...
        currentLimitActive1(k), ...
        stalledState1(k) ...
    ] = steadyStateOperatingPoint( ...
        commandedVoltage1(k), ...
        loadTorque1(k), ...
        motor, ...
        case1.minimumCurrent, ...
        case1.maximumCurrent ...
    );

end


%% ========================================================================
%  13. CASE 1 RPM
%  ========================================================================

motorRPM1 = ...
    angularVelocity1 * ...
    60/(2*pi);


%% ========================================================================
%  14. CASE 1 STALL DETECTION
%  ========================================================================

stallIndex1 = find( ...
    stalledState1 & ...
    loadTorque1 > ...
    case1.initialLoadTorque, ...
    1, ...
    'first' ...
);


if ~isempty(stallIndex1)

    stallDetected1 = true;

    lastIndex1 = ...
        stallIndex1;

else

    stallDetected1 = false;

    lastIndex1 = ...
        length(loadTorque1);

end


%% Keep only points up to stall

loadTorque1 = ...
    loadTorque1(1:lastIndex1);


commandedVoltage1 = ...
    commandedVoltage1(1:lastIndex1);


current1 = ...
    current1(1:lastIndex1);


angularVelocity1 = ...
    angularVelocity1(1:lastIndex1);


effectiveVoltage1 = ...
    effectiveVoltage1(1:lastIndex1);


currentLimitActive1 = ...
    currentLimitActive1(1:lastIndex1);


stalledState1 = ...
    stalledState1(1:lastIndex1);


motorRPM1 = ...
    motorRPM1(1:lastIndex1);


%% ========================================================================
%  15. CASE 1 MOTOR VARIABLES
%  ========================================================================

%% Electromagnetic motor torque

motorTorque1 = ...
    motor.Kt .* ...
    current1;


%% Back EMF

backEMF1 = ...
    motor.Ke .* ...
    angularVelocity1;


%% Friction torque

frictionTorque1 = ...
    motor.B .* ...
    angularVelocity1;


%% Net torque

netTorque1 = ...
    motorTorque1 - ...
    loadTorque1 - ...
    frictionTorque1;


%% ========================================================================
%  16. CASE 1 POWERS
%  ========================================================================

%% Electrical input power

electricalPower1 = ...
    effectiveVoltage1 .* ...
    current1;


%% Electromagnetic mechanical power

motorMechanicalPower1 = ...
    motorTorque1 .* ...
    angularVelocity1;


%% Useful load power

loadMechanicalPower1 = ...
    loadTorque1 .* ...
    angularVelocity1;


%% ========================================================================
%  17. CASE 1 STEADY-STATE EFFICIENCY
%  ========================================================================

% Useful output power:
%
%       Pout = Tload * omega
%
% Electrical input power:
%
%       Pin = Veff * i
%
% Efficiency:
%
%                Pout
%       eta = ----------- * 100
%                Pin


efficiency1 = ...
    zeros(size(loadTorque1));


validEfficiency1 = ...
    electricalPower1 > 1e-12;


efficiency1(validEfficiency1) = ...
    100 .* ...
    loadMechanicalPower1(validEfficiency1) ./ ...
    electricalPower1(validEfficiency1);


efficiency1 = ...
    min( ...
        max( ...
            efficiency1, ...
            0 ...
        ), ...
        100 ...
    );


%% ========================================================================
%  18. CASE 1 RESULTS
%  ========================================================================

fprintf('\n============================================================\n');
