%% ========================================================================
%  57BLDC75-20730-08B21 MOTOR - STEADY-STATE CHARACTERIZATION
%
%  ONLY STEADY-STATE OPERATING POINTS ARE CALCULATED:
%
%       di/dt     = 0
%       domega/dt = 0
%
%  Therefore:
%
%       0 = V - R*i - Ke*omega
%       0 = Kt*i - B*omega - Tload
%
%
%  CASE 1:
%    - Constant voltage = 24 V
%    - Load torque increases from 0 to the selected maximum
%    - Current limit selectable:
%         1.0 A -> Driver limit
%         4.8 A -> Motor rated-current limit
%
%    FIGURE:
%       Current    vs Load Torque
%       Efficiency vs Load Torque
%       Power      vs Load Torque
%       RPM        vs Load Torque
%
%
%  CASE 2:
%    - Zero external load torque
%    - Voltage sweep from 6 V to 24 V
%    - Current limit selectable:
%         1.0 A -> Driver limit
%         4.8 A -> Motor rated-current limit
%
%    FIGURE:
%       RPM vs Commanded Voltage
%
%
%  OUTPUT:
%
%    Figure 1:
%       Case1_LoadTorque_Characteristics.png
%
%    Figure 2:
%       Case2_Voltage_vs_RPM.png
%
%    Excel:
%       Motor_Simulation_Results.xlsx
%
% ========================================================================

clear;
clc;
close all force;


%% ========================================================================
%  1. MOTOR PARAMETERS
%  ========================================================================

motor.model = '57BLDC75-20730-08B21';


%% Datasheet identification

motor.numberOfPoles  = 4;
motor.numberOfPhases = 3;


%% Datasheet operating parameters

motor.nominalVoltage = 24;      % [V]

motor.ratedSpeedRPM  = 4000;    % [RPM]

motor.ratedTorque    = 0.22;    % [N*m]

motor.ratedCurrent   = 4.8;     % [A]

motor.ratedPower     = 70;      % [W]

motor.peakTorque     = 0.66;    % [N*m]

motor.peakCurrent    = 14.4;    % [A]


%% ========================================================================
%  2. TORQUE CONSTANT
%  ========================================================================

motor.Kt = 0.06;                % [N*m/A]


%% ========================================================================
%  3. BACK-EMF CONSTANT
%  ========================================================================

motor.Ke_V_per_kRPM = 6.6;      % [V/kRPM]


motor.Ke = ...
    motor.Ke_V_per_kRPM / ...
    (1000*2*pi/60);             % [V/(rad/s)]


%% ========================================================================
%  4. ELECTRICAL PARAMETERS
%  ========================================================================

motor.R = 0.48;                 % [ohm]

motor.L = 1.17e-3;              % [H]


%% ========================================================================
%  5. ROTOR AND LOAD INERTIA
%  ========================================================================

motor.rotorInertia_gcm2 = 119;  % [g*cm^2]


motor.Jmotor = ...
    motor.rotorInertia_gcm2 * ...
    1e-7;                       % [kg*m^2]


motor.Jload = 2.5e-4;           % [kg*m^2]


motor.J = ...
    motor.Jmotor + ...
    motor.Jload;                % [kg*m^2]


%% ========================================================================
%  6. VISCOUS FRICTION COEFFICIENT
%  ========================================================================

motor.noLoadCurrent = 0.3;      % [A]

motor.noLoadSpeedRPM = 4000;    % [RPM]


motor.noLoadAngularVelocity = ...
    motor.noLoadSpeedRPM * ...
    2*pi/60;                    % [rad/s]


motor.B = ...
    motor.Kt * ...
    motor.noLoadCurrent / ...
    motor.noLoadAngularVelocity;
                                % [N*m*s/rad]


%% ========================================================================
%  7. GENERAL CHARACTERIZATION PARAMETERS
%  ========================================================================

simulation.numberOfOperatingPoints = 3000;

simulation.maximumPlotPoints = 3000;


%% ========================================================================
%  8. GRAPHICS AND FILE SETTINGS
%  ========================================================================

set( ...
    groot, ...
    'defaultFigureRenderer', ...
    'painters' ...
);


output.figure1File = ...
    'Case1_LoadTorque_Characteristics.png';


output.figure2File = ...
    'Case2_Voltage_vs_RPM.png';


output.excelFile = ...
    'Motor_Simulation_Results.xlsx';


output.figureResolution = 300;


%% ========================================================================
%  9. PRINT MOTOR PARAMETERS
%  ========================================================================

fprintf('\n============================================================\n');
fprintf('57BLDC75-20730-08B21 STEADY-STATE MOTOR MODEL\n');
fprintf('============================================================\n');


fprintf('\nMotor parameters:\n\n');


fprintf( ...
    'Resistance:                 %.6f ohm\n', ...
    motor.R ...
);


fprintf( ...
    'Inductance:                 %.6e H\n', ...
    motor.L ...
